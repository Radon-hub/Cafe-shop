CREATE SEQUENCE cat_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE prod_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE inv_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE categories
(
    id         BIGINT                      NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    name       VARCHAR(255)                NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE warehouses
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    name       VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_warehouses PRIMARY KEY (id),
    CONSTRAINT uq_warehouses_name UNIQUE (name)
);

CREATE TABLE products
(
    id           BIGINT                      NOT NULL,
    created_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    name         VARCHAR(255)                NOT NULL,
    description  VARCHAR(255)                NOT NULL,
    price        NUMERIC(38, 2)              NOT NULL,
    weight       NUMERIC(38, 2)              NOT NULL,
    category_id  BIGINT                      NOT NULL,
    inventory_id BIGINT,
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT uq_products_inventory UNIQUE (inventory_id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE inventory
(
    id           BIGINT                      NOT NULL,
    created_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    count        INTEGER                     NOT NULL,
    product_id   BIGINT                      NOT NULL,
    warehouse_id BIGINT                      NOT NULL,
    CONSTRAINT pk_inventory PRIMARY KEY (id),
    CONSTRAINT uq_inventory_product UNIQUE (product_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_inventory_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (id)
);

-- products <-> inventory point at each other, so this FK is added after both exist
ALTER TABLE products
    ADD CONSTRAINT fk_products_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id);

CREATE INDEX idx_product_name ON products (name);
CREATE INDEX idx_product_category ON products (category_id);